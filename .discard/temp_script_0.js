    // Matrix Filter Pills
    document.querySelectorAll('.matrix-filter-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        document.querySelectorAll('.matrix-filter-btn').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        currentMatrixFilter = btn.getAttribute('data-matrix-filter');

        if (currentMatrixFilter === 'MANUALS') {
          document.getElementById('manualsVaultSection').scrollIntoView({ behavior: 'smooth' });
        } else {
          renderStudyMatrix();
          document.getElementById('matrixCard').scrollIntoView({ behavior: 'smooth' });
        }
      });
    });

    // Keyboard Shortcuts
    window.addEventListener('keydown', (e) => {
      if (e.target.tagName === 'INPUT') {
        if (e.key === 'Escape') {
          searchInput.value = '';
          searchClearBtn.style.display = 'none';
          renderSidebar();
          filterMatrixTable('');
          searchInput.blur();
        }
        return;
      }

      if (e.key === '[' || (e.ctrlKey && e.key.toLowerCase() === 'b')) {
        e.preventDefault();
        toggleSidebar();
      } else if (e.key === '/' || (e.ctrlKey && e.key === 'k')) {
        e.preventDefault();
        searchInput.focus();
      } else if (e.key === 'Escape') {
        if (studyDesk.style.display === 'none') {
          returnToDesk();
        } else if (searchInput.value) {
          searchInput.value = '';
          searchClearBtn.style.display = 'none';
          renderSidebar();
          filterMatrixTable('');
        }
      } else if (e.key.toLowerCase() === 's') {
        openSyllabus();
      } else if (e.key.toLowerCase() === 'q') {
        if (btnToggleQ && !btnToggleQ.disabled && currentSessionData) {
          btnToggleQ.click();
        }
      } else if (e.key.toLowerCase() === 'a') {
        if (btnToggleA && !btnToggleA.disabled && currentSessionData) {
          btnToggleA.click();
        }
      } else if (e.key.toLowerCase() === 'f') {
        toggleFullscreen();
      } else if (e.key === 'ArrowLeft') {
        if (btnPrevSession && !btnPrevSession.disabled && currentSessionData) {
          btnPrevSession.click();
        }
      } else if (e.key === 'ArrowRight') {
        if (btnNextSession && !btnNextSession.disabled && currentSessionData) {
          btnNextSession.click();
        }
      }
    });

    // Initial renders
    renderSidebar();
    renderStudyMatrix();
    renderManualsVault();
